export const mockFEFOItems: BatchItemFEFO[] = mockBatches
  .filter((batch) => batch.current_quantity > 0)
  .map((batch) => {
    const medication = mockMedications.find(
      (item) => item.id === batch.medication_id,
    );
    const location = mockLocations.find(
      (item) => item.id === batch.location_id,
    );

    if (!medication || !location) {
      throw new Error(`Mock batch ${batch.id} has an invalid medication or location.`);
    }

    return {
      batch_id: batch.id,
      trade_name: medication.trade_name,
      active_ingredient: medication.active_ingredient,
      concentration: medication.concentration,
      batch_number: batch.batch_number,
      expiration_date: batch.expiration_date,
      days_until_expiration: Math.floor(
        (new Date(`${batch.expiration_date}T00:00:00Z`).getTime() -
          new Date(`${new Date().toISOString().slice(0, 10)}T00:00:00Z`).getTime()) /
          86_400_000,
      ),
      current_quantity: batch.current_quantity,
      location_code: location.location_code,
      zone: location.zone,
      requires_refrigeration: medication.requires_refrigeration,
      requires_prescription: medication.requires_prescription,
    };
  })
  .sort((first, second) =>
    first.expiration_date.localeCompare(second.expiration_date),
  );
